package com.portfoliopro.dto;

import java.math.BigDecimal;

public class AuthDTOs {

    public static class LoginRequest {
        private String email;
        private String password;

        public String getEmail() { return email; }
        public void setEmail(String email) { this.email = email; }
        public String getPassword() { return password; }
        public void setPassword(String password) { this.password = password; }
    }

    public static class RegisterRequest {
        private String name;
        private String email;
        private String password;
        private String role; // Optional, defaults to "USER"

        public String getName() { return name; }
        public void setName(String name) { this.name = name; }
        public String getEmail() { return email; }
        public void setEmail(String email) { this.email = email; }
        public String getPassword() { return password; }
        public void setPassword(String password) { this.password = password; }
        public String getRole() { return role; }
        public void setRole(String role) { this.role = role; }
    }

    public static class AuthResponse {
        private String token;
        private UserDto user;

        public AuthResponse(String token, UserDto user) {
            this.token = token;
            this.user = user;
        }

        public String getToken() { return token; }
        public void setToken(String token) { this.token = token; }
        public UserDto getUser() { return user; }
        public void setUser(UserDto user) { this.user = user; }
    }

    public static class UserDto {
        private Long id;
        private String name;
        private String email;
        private String role;
        private BigDecimal virtualBalance;

        public UserDto() {}

        public UserDto(Long id, String name, String email, String role, BigDecimal virtualBalance) {
            this.id = id;
            this.name = name;
            this.email = email;
            this.role = role;
            this.virtualBalance = virtualBalance;
        }

        public Long getId() { return id; }
        public void setId(Long id) { this.id = id; }
        public String getName() { return name; }
        public void setName(String name) { this.name = name; }
        public String getEmail() { return email; }
        public void setEmail(String email) { this.email = email; }
        public String getRole() { return role; }
        public void setRole(String role) { this.role = role; }
        public BigDecimal getVirtualBalance() { return virtualBalance; }
        public void setVirtualBalance(BigDecimal virtualBalance) { this.virtualBalance = virtualBalance; }
    }
}
